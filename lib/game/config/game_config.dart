import 'dart:ui';

/// 游戏全局调参中心。
///
/// 设计原则：所有影响手感的数值集中在此，禁止在组件内散落魔法数字。
/// 调参时只需改这一个文件，且能保证各系统（物理、生成、难度）彼此一致。
///
/// 单位约定：
/// - 距离使用「逻辑像素」；游戏以固定设计基准宽高 [designSize] 进行布局，
///   再按屏幕尺寸整体缩放，从而保证不同机型上管道间距/缝隙的手感一致。
/// - 时间使用秒（Flame 的 `dt` 为秒）。
///
/// 调参溯源：以下重力、跳跃速度、缝隙尺寸等基准值参考经典 Flappy Bird 手感
/// （见 README「参考项目」章节），并针对固定步长循环重新标定。
class GameConfig {
  GameConfig._();

  /// 逻辑设计分辨率。所有布局常量以该基准推导，绘制时按屏幕等比缩放。
  /// 采用 9:16 竖屏比例，与主流手机接近，可减少缩放失真。
  static const Size designSize = Size(360, 640);

  // ---------------------------------------------------------------------------
  // 小鸟物理
  // ---------------------------------------------------------------------------

  /// 重力加速度（逻辑像素/秒²）。
  /// 数值偏大能带来「突然下坠」的紧张感，是 Flappy Bird 手感的核心。
  static const double gravity = 1400.0;

  /// 每次点击获得的向上瞬时速度（逻辑像素/秒，负值表示向上）。
  /// 与 [gravity] 的比值决定「跳跃高度」：约 168px，接近屏幕高度的 1/4。
  static const double flapVelocity = -420.0;

  /// 下落速度上限，防止长时间下坠后速度失控导致穿模。
  static const double maxFallVelocity = 700.0;

  /// 小鸟碰撞半径（逻辑像素）。
  /// 刻意小于贴图尺寸（约 34x24），让判定更「宽容」——这是经典 Flappy Bird
  /// 广受好评的设计：视觉上蹭到了边缘但实际不算撞，降低挫败感。
  static const double birdHitboxRadius = 11.0;

  /// 小鸟初始 X 位置（逻辑像素），约在屏幕左侧 1/4 处。
  static const double birdStartX = 92.0;

  // ---------------------------------------------------------------------------
  // 管道
  // ---------------------------------------------------------------------------

  /// 管道宽度（逻辑像素）。偏窄可增加反应窗口。
  static const double pipeWidth = 62.0;

  /// 起始缝隙高度（逻辑像素）。管道上下之间的可通过空间。
  static const double pipeGapStart = 165.0;

  /// 缝隙能缩到的最小值。低于此值即便完美操作也无法通过。
  static const double pipeGapMin = 110.0;

  /// 每得 1 分缝隙收窄的像素数，构成难度递增的第一条曲线。
  static const double pipeGapShrinkPerPoint = 2.6;

  /// 管道水平移动速度（逻辑像素/秒）。主难度杠杆。
  static const double pipeSpeedStart = 118.0;

  /// 速度上限，避免后期快到不可玩。
  static const double pipeSpeedMax = 225.0;

  /// 每得 1 分速度增加量，构成难度递增的第二条曲线。
  static const double pipeSpeedIncreasePerPoint = 2.2;

  /// 相邻两组管道的水平间距（逻辑像素）。
  /// 与 [pipeSpeedStart] 共同决定「通过一组管道后到下一组的反应时间」，约 1.8 秒。
  static const double pipeSpacing = 215.0;

  /// 首组管道相对屏幕右边缘的额外进入距离（逻辑像素）。
  ///
  /// 这是开局手感的关键参数：首组管道必须在小鸟坠地之前进入视野，
  /// 否则玩家会在「还没看到任何障碍」的情况下就撞地，体验极差。
  ///
  /// 取值依据：小鸟从出生高度（约屏幕 45%）自由落体到地面约需 0.65 秒，
  /// 加上一段容错缓冲，首组管道应在此时间内可见。
  /// 因此初始生成距离取一个较小值（而非 [pipeSpacing]），让首组管道尽快出现。
  static const double firstPipeLeadIn = 60.0;

  /// 缝隙中心的允许活动范围（相对于屏幕高度的比例）。
  /// 0.18~0.82 保证缝隙不会贴到天花板或地面，避免出现「必死」管道。
  static const double gapCenterMinRatio = 0.18;
  static const double gapCenterMaxRatio = 0.82;

  /// 缝隙中心相对上一组的最大垂直跳变比例。
  /// 限制相邻管道的高低差，防止出现需要瞬间大幅上升的「不可能」组合。
  static const double gapCenterMaxDeltaRatio = 0.30;

  // ---------------------------------------------------------------------------
  // 地面与滚动
  // ---------------------------------------------------------------------------

  /// 地面高度（逻辑像素）。地面参与碰撞，小鸟触地即死亡。
  static const double groundHeight = 96.0;

  /// 地面滚动贴图速度（逻辑像素/秒）。比管道慢一些以营造视差纵深感。
  static const double groundScrollSpeed = 118.0;

  /// 背景远景滚动速度，进一步制造视差层次。
  static const double backgroundScrollSpeed = 22.0;

  // ---------------------------------------------------------------------------
  // 计分与规则
  // ---------------------------------------------------------------------------

  /// 达到 10 的整数倍分数时，在画面上短暂提示难度已提升。
  static const int difficultyNoticeInterval = 10;

  /// 屏幕点击后进入游戏状态的输入冷却（秒）。
  /// 防止「死亡瞬间的连点」被误判为「立刻重开 + 起飞」。
  static const double inputCooldown = 0.25;

  /// 起飞缓冲时间（秒）。
  ///
  /// 点击开始游戏后，小鸟先保持悬停 [launchGracePeriod] 秒，此期间：
  /// - 不受重力影响（避免玩家还没反应过来就坠地）
  /// - 管道照常生成并滚动（让玩家看清即将到来的障碍）
  /// - 玩家在此期间点击仍然有效（可提前起飞）
  ///
  /// 这是对「开局即下坠」这一体验缺陷的修正。原版 Flappy Bird 采用
  /// 「悬停待机 → 首次点击才开始」的两段式，本参数等价于给玩家一段
  /// 可操作的准备时间。
  ///
  /// 取值 0.75 秒：足够完成一次视觉定位，又不至于让人觉得「点了没反应」。
  static const double launchGracePeriod = 0.75;

  // ---------------------------------------------------------------------------
  // 渲染与计时
  // ---------------------------------------------------------------------------

  /// 固定物理步长（秒）。以 120Hz 子步推进物理，使高刷新率屏幕手感一致。
  /// 详见 [GameWorld.update] 中的子步积分实现。
  static const double fixedTimeStep = 1 / 120;

  /// 单帧允许推进的最大时间，防止应用切回前台时出现「巨大 dt」导致小鸟瞬移。
  static const double maxFrameTime = 0.1;
}
